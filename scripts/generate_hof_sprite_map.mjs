// Generates frontend/src/utils/hofSpriteMap.ts from the ROM species list and
// the full-sprite folders. The Hall of Fame diorama needs to resolve a species
// name to an exact sprite filename without shipping the sprite folders to the
// client, so the mapping is precomputed here whenever assets/species change.
//
// Usage: node scripts/generate_hof_sprite_map.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const publicDir = path.join(repoRoot, 'frontend', 'public');

const speciesText = fs.readFileSync(
  path.join(repoRoot, 'frontend/src/utils/speciesIdMap.ts'),
  'utf8',
);
const species = [
  ...speciesText.matchAll(
    /(\d+):\s*\{\s*name:\s*"([^"]+)",\s*icon:\s*"([^"]+)",\s*baseId:\s*(\d+),\s*form:\s*"([^"]*)"/g,
  ),
].map((match) => ({
  id: Number(match[1]),
  name: match[2],
  icon: match[3],
  baseId: Number(match[4]),
}));
const speciesById = new Map(species.map((entry) => [entry.id, entry]));

const normalize = (value) =>
  value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '');

const readFolder = (folder) =>
  fs
    .readdirSync(path.join(publicDir, folder))
    .filter((file) => file.endsWith('.png'))
    .map((file) => ({
      file,
      url: encodeURI(`/${folder}/${file}`),
      key: normalize(path.basename(file, '.png')),
    }));

// Evolution sprites win when both folders contain a matching name.
const spriteFiles = [...readFolder('evolutions'), ...readFolder('baseforms')];
const spriteByKey = new Map();
for (const sprite of spriteFiles) {
  if (sprite.key && !spriteByKey.has(sprite.key)) spriteByKey.set(sprite.key, sprite.url);
}

// Filename conventions the ROM species names can't be normalized into.
const NAME_ALIASES = {
  basculegionm: 'basculegionmale',
  basculegionf: 'basculegionfemale',
  nidoranf: 'nidoran',
  nidoranm: 'nidoran',
  flabebered: 'flabebe',
  flabebeyellow: 'flabebe',
  flabebeorange: 'flabebe',
  flabebeblue: 'flabebe',
  flabebewhite: 'flabebe',
};

const findSprite = (keys) => {
  for (const key of keys) {
    const sprite = spriteByKey.get(NAME_ALIASES[key] ?? key);
    if (sprite) return sprite;
  }
  return null;
};

const buildMap = (keySelector) => {
  const map = {};
  for (const entry of species) {
    const key = normalize(keySelector(entry));
    if (!key || key in map) continue;
    const base = speciesById.get(entry.baseId);
    const sprite = findSprite([
      key,
      normalize(entry.icon),
      base ? normalize(base.name) : '',
      base ? normalize(base.icon) : '',
    ]);
    if (sprite) map[key] = sprite;
  }
  return map;
};

const byName = buildMap((entry) => entry.name);
const byIcon = buildMap((entry) => entry.icon);

// Draft-pool entries that don't correspond 1:1 with a ROM species name.
for (const name of ['Plusle and Minun']) {
  const key = normalize(name);
  const sprite = findSprite([key]);
  if (sprite) byName[key] = sprite;
}
// Icons sometimes use the abbreviated species name that the display name
// doesn't (Basculegion-M -> basculegion-m); map that alias as well.
for (const [alias, target] of Object.entries(NAME_ALIASES)) {
  if (byIcon[target]) byIcon[alias] = byIcon[target];
}

const serialize = (map) =>
  Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n');

const output = `// Auto-generated by scripts/generate_hof_sprite_map.mjs.
// Do not edit by hand. Regenerate after changing species.h or the sprite folders.
export const HOF_SPRITE_BY_NAME: Readonly<Record<string, string>> = {
${serialize(byName)}
};

export const HOF_SPRITE_BY_ICON: Readonly<Record<string, string>> = {
${serialize(byIcon)}
};
`;

fs.writeFileSync(
  path.join(repoRoot, 'frontend/src/utils/hofSpriteMap.ts'),
  output,
);
console.log(`Wrote ${Object.keys(byName).length} name and ${Object.keys(byIcon).length} icon mappings.`);
